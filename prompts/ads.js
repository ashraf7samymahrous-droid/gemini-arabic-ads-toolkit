/**
 * برومبتات جاهزة لكتابة إعلانات - فصحى ودارجة
 */

const adPrompts = {
  // إعلان بالفصحى - أسلوب احترافي
  formal: (product, audience, tone = "احترافي") => `
اكتب إعلاناً تسويقياً بالعربية الفصحى لمنتج/خدمة: "${product}"
الجمهور المستهدف: ${audience}
النبرة: ${tone}

المتطلبات:
- جملة افتتاحية تجذب الانتباه فوراً
- 2-3 نقاط توضح الفائدة الأساسية (ماشي المواصفات، الفائدة اللي يحس بيها الزبون)
- دعوة للعمل (Call to Action) واضحة ومباشرة
- الطول: بين 40-70 كلمة، مناسب لمنشور سوشيال ميديا
`,

  // إعلان بالدارجة الجزائرية - أسلوب قريب من الزبون
  dialect: (product, audience) => `
اكتب إعلاناً بالدارجة الجزائرية (العامية) لـ: "${product}"
الجمهور: ${audience}

المتطلبات:
- استعمل لهجة جزائرية طبيعية، ماشي فصحى مخلوطة بكلمات دارجة بطريقة مصطنعة
- أسلوب قريب ومباشر، كأنك تحكي مع صاحبك
- خليه قصير وضارب (30-50 كلمة)
- زيد إيموجي مناسب لو يلزم
- دعوة للتواصل فالآخر (واتساب، دير طلبك، تواصل معنا...)
`,

  // عنوان/هوك جذاب فقط (للاختبار السريع لعدة أفكار)
  hookOnly: (product, count = 5) => `
اكتبلي ${count} عناوين/هوكات قصيرة ومختلفة (بالدارجة الجزائرية) لجذب الانتباه لمنتج: "${product}"
كل هوك سطر وحد، بلا شرح، بلا ترقيم إضافي غير رقم بسيط.
`,

  // إعلان لمناسبة/تخفيض
  promo: (product, discount, deadline) => `
اكتب إعلان ترويجي (دارجة جزائرية، حماسي بصح ماشي مبالغ فيه) لـ:
المنتج: "${product}"
التخفيض: ${discount}
آخر أجل: ${deadline}

خليه يحس بالإلحاح (urgency) بلا ما يبان كذاب أو مبالغ فيه.
`,

  // إعلان لقصة/ستوري (Instagram/Facebook Story) - قصير جداً
  story: (product) => `
اكتب نص قصير لستوري (Story) بالدارجة الجزائرية لـ: "${product}"
- سطر واحد لسطرين بس
- أسلوب حماسي وسريع، كأنه "لمحة" مش إعلان كامل
- بلا مقدمات
`,

  // مقارنة (قبل/بعد) - بدون تسمية منافس بالاسم
  comparison: (product, painPoint) => `
اكتب إعلاناً بالدارجة الجزائرية يبرز الفرق بين المشكلة والحل:
المشكلة اللي يعانيها الزبون: "${painPoint}"
الحل: "${product}"
أسلوب: "قبل/بعد" بسيط، بلا ذكر أي منافس بالاسم.
`,

  // إعلان لمحل/خدمة محلية
  local: (business, city, offer) => `
اكتب إعلاناً بالدارجة الجزائرية لمحل/خدمة محلية:
النشاط: "${business}"
المدينة/الحي: "${city}"
العرض: "${offer}"
خليه يحس بالقرب المحلي (زي "حنا فـ ${city}" أو إشارة للحومة).
`,

  // تعليق على منشور (رد تفاعلي جاهز)
  captionReply: (context) => `
اكتب رد تعليق قصير وودود بالدارجة الجزائرية على تعليق زبون:
السياق: "${context}"
خليه طبيعي، ماشي جامد كأنه بوت.
`
};

module.exports = { adPrompts };
